import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";

const here = dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = join(here, "..", "..", "..", "supabase", "migrations");

export interface TenantDb {
  db: PGlite;
  close: () => Promise<void>;
  /** Run statements as the given user id under the least-privilege app role. */
  asUser: (userId: string | null, sql: string, params?: unknown[]) => Promise<unknown[]>;
  /** Run statements as superuser (seeding only — never in product paths). */
  asSuperuser: (sql: string, params?: unknown[]) => Promise<unknown[]>;
}

/** Fresh in-process Postgres with all migrations applied + Supabase-compatible shims. */
export async function newTenantDb(): Promise<TenantDb> {
  const db = new PGlite();
  // Supabase-provided roles referenced by migrations (exist in prod; stubbed here).
  await db.exec(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN;`);
  // Least-privilege app role used by every test (proves RLS, not superuser).
  await db.exec(`CREATE ROLE app_user NOLOGIN;`);
  // auth.uid() stub — test-only, created BEFORE migrations because CREATE POLICY
  // resolves referenced functions eagerly. (In prod Supabase provides auth.uid();
  // the stub NEVER ships in migrations.)
  await db.exec(`
    CREATE SCHEMA IF NOT EXISTS auth;
    CREATE OR REPLACE FUNCTION auth.uid() RETURNS UUID
    LANGUAGE sql STABLE
    AS $$ SELECT NULLIF(current_setting('app.test_uid', true), '')::UUID $$;
  `);
  // (Granted after migrations below — migration 0001 creates schema formos.)

  const files = readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  for (const f of files) {
    await db.exec(readFileSync(join(MIGRATIONS_DIR, f), "utf8"));
  }
  // USAGE on schemas mirrors Supabase's default authenticated-role grants.
  // (Granted after migrations because migration 0001 creates schema formos.)
  await db.exec(`GRANT USAGE ON SCHEMA public, formos, auth TO app_user;`);
  // Inherit prod table grants: in Supabase, PostgREST serves requests as the
  // `authenticated` role; here app_user inherits it so GRANTs behave identically.
  await db.exec(`GRANT authenticated TO app_user;`);

  const asUser = async (userId: string | null, sql: string, params: unknown[] = []) => {
    await db.query(`SET ROLE app_user`);
    if (userId === null) {
      await db.query(`RESET app.test_uid`);
    } else {
      // identifiers are UUIDs generated by tests; validated format before interpolation.
      if (!/^[0-9a-f-]{36}$/i.test(userId)) throw new Error("bad test user id");
      await db.query(`SET app.test_uid = '${userId}'`);
    }
    try {
      const res = await db.query(sql, params as never[]);
      return res.rows;
    } finally {
      await db.query(`RESET ROLE`);
    }
  };

  const asSuperuser = async (sql: string, params: unknown[] = []) => {
    const res = await db.query(sql, params as never[]);
    return res.rows;
  };

  return { db, close: () => db.close(), asUser, asSuperuser };
}

/** Deterministic test UUIDs (uuidv4-shaped; validity only matters for the uuid type). */
export const uuid = (n: number): string => {
  const h = n.toString(16).padStart(2, "0");
  return `00000000-0000-4000-8000-0000000000${h}`;
};
